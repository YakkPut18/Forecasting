from statsmodels.graphics.tsaplots import plot_acf, plot_pacf

# Apply seasonal differencing (lag 12) to the already first-differenced training series
train_data_diff_seasonal_diff = train_data_diff.diff(periods=12).dropna()

plt.figure(figsize=(10,4))
