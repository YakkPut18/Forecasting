# ADF test for stationarity on the first-differenced training data
res_train_diff1 = adfuller(train_data_diff)
print('ADF stat (first-differenced train data):', res_train_diff1[0], 'p-value:', res_train_diff1[1])
if res_train_diff1[1] > 0.05:
    print('First-differenced training data is likely non-stationary (p-value > 0.05).')
else:
    print('First-differenced training data is likely stationary (p-value <= 0.05).')

# ACF and PACF plots for the first-differenced training series
plt.figure(figsize=(12, 8))
plot_acf(train_data_diff, lags=40, ax=plt.gca(), zero=False)
plt.title('ACF — First-differenced Konsumsi (Training Data)')
